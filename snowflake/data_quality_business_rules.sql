USE DATABASE RECRUITMENT_DB;
USE SCHEMA CANDIDATE_00395;

-- ====================
-- 1. DATA QUALITY ISSUES IDENTIFICATION
-- ====================

-- Issue 1: Inconsistent Boolean Values
-- Problem: CANCELLED and DIVERTED fields contain mixed formats
-- Sample values found: 'True', 'False', '1', '0', 'Y', 'N', 'F', 'T'
SELECT 
    'Boolean Inconsistencies' AS "ISSUE_TYPE",
    COUNT(*) AS "TOTAL_RECORDS",
    COUNT(DISTINCT "CANCELLED") AS "CANCELLED_VARIATIONS",
    COUNT(DISTINCT "DIVERTED") AS "DIVERTED_VARIATIONS"
FROM "STAGING_FLIGHTS_RAW";

-- Show actual boolean variations
SELECT 
    "CANCELLED",
    "DIVERTED", 
    COUNT(*) AS "RECORD_COUNT"
FROM "STAGING_FLIGHTS_RAW"
GROUP BY "CANCELLED", "DIVERTED"
ORDER BY "RECORD_COUNT" DESC;

-- Issue 2: Contaminated Text Fields
-- Problem: Airline and airport names contain concatenated codes/descriptions
-- Examples: "DL: Delta Air Lines Inc.", "CharlestonSC: Charleston AFB/International"
SELECT 
    'Text Field Contamination' AS "ISSUE_TYPE",
    COUNT(CASE WHEN "AIRLINENAME" LIKE '%:%' THEN 1 END) AS "CONTAMINATED_AIRLINES",
    COUNT(CASE WHEN "ORIGAIRPORTNAME" LIKE '%:%' THEN 1 END) AS "CONTAMINATED_ORIGIN_AIRPORTS",
    COUNT(CASE WHEN "DESTAIRPORTNAME" LIKE '%:%' THEN 1 END) AS "CONTAMINATED_DEST_AIRPORTS",
    COUNT(*) AS "TOTAL_RECORDS"
FROM "STAGING_FLIGHTS_RAW";

-- Issue 3: Time Format Complexity & Invalid Values
-- AVIATION TIME DEFINITIONS:
-- DEPTIME/ARRTIME: Actual departure/arrival times (HHMM format)
-- CRSDEPTIME/CRSARRTIME: Scheduled departure/arrival times (HHMM format)  
-- WHEELSOFF: Time when aircraft wheels leave the ground (takeoff)
-- WHEELSON: Time when aircraft wheels touch the ground (landing)
-- TAXIOUT/TAXIIN: Taxi time in minutes (duration, not time)
-- DEPDELAY/ARRDELAY: Delay in minutes (positive=late, negative=early)
-- CRSELAPSEDTIME/ACTUALELAPSEDTIME: Flight duration in minutes (not HHMM time format)

SELECT 
    'Time Format Issues' AS "ISSUE_TYPE",
    COUNT(CASE WHEN LENGTH("DEPTIME") BETWEEN 3 AND 4 AND "DEPTIME" NOT LIKE '%:%' THEN 1 END) AS "INTEGER_FORMAT_TIMES",
    COUNT(CASE WHEN "DEPTIME" IS NULL AND "CANCELLED" != '1' AND "CANCELLED" != 'True' THEN 1 END) AS "MISSING_TIMES_NON_CANCELLED",
    
    -- CRITICAL: Invalid time values (2400+ should be 0000-2359) for TIME fields
    COUNT(CASE WHEN TRY_CAST("DEPTIME" AS INTEGER) >= 2400 THEN 1 END) AS "INVALID_DEPTIME_2400_PLUS",
    COUNT(CASE WHEN TRY_CAST("ARRTIME" AS INTEGER) >= 2400 THEN 1 END) AS "INVALID_ARRTIME_2400_PLUS", 
    COUNT(CASE WHEN TRY_CAST("CRSDEPTIME" AS INTEGER) >= 2400 THEN 1 END) AS "INVALID_CRSDEPTIME_2400_PLUS",
    COUNT(CASE WHEN TRY_CAST("CRSARRTIME" AS INTEGER) >= 2400 THEN 1 END) AS "INVALID_CRSARRTIME_2400_PLUS",
    COUNT(CASE WHEN TRY_CAST("WHEELSOFF" AS INTEGER) >= 2400 THEN 1 END) AS "INVALID_WHEELSOFF_2400_PLUS",
    COUNT(CASE WHEN TRY_CAST("WHEELSON" AS INTEGER) >= 2400 THEN 1 END) AS "INVALID_WHEELSON_2400_PLUS",
    
    -- Invalid minute values (should be 00-59) for TIME fields
    COUNT(CASE WHEN MOD(TRY_CAST("DEPTIME" AS INTEGER), 100) >= 60 THEN 1 END) AS "INVALID_DEPTIME_MINUTES",
    COUNT(CASE WHEN MOD(TRY_CAST("ARRTIME" AS INTEGER), 100) >= 60 THEN 1 END) AS "INVALID_ARRTIME_MINUTES",
    COUNT(CASE WHEN MOD(TRY_CAST("CRSDEPTIME" AS INTEGER), 100) >= 60 THEN 1 END) AS "INVALID_CRSDEPTIME_MINUTES",
    COUNT(CASE WHEN MOD(TRY_CAST("CRSARRTIME" AS INTEGER), 100) >= 60 THEN 1 END) AS "INVALID_CRSARRTIME_MINUTES",
    COUNT(CASE WHEN MOD(TRY_CAST("WHEELSOFF" AS INTEGER), 100) >= 60 THEN 1 END) AS "INVALID_WHEELSOFF_MINUTES",
    COUNT(CASE WHEN MOD(TRY_CAST("WHEELSON" AS INTEGER), 100) >= 60 THEN 1 END) AS "INVALID_WHEELSON_MINUTES",
    
    -- DURATION field validation (these are minutes, not HHMM time format)
    COUNT(CASE WHEN TRY_CAST("CRSELAPSEDTIME" AS INTEGER) < 0 THEN 1 END) AS "NEGATIVE_SCHEDULED_DURATION",
    COUNT(CASE WHEN TRY_CAST("ACTUALELAPSEDTIME" AS INTEGER) < 0 THEN 1 END) AS "NEGATIVE_ACTUAL_DURATION",
    COUNT(CASE WHEN TRY_CAST("CRSELAPSEDTIME" AS INTEGER) > 1440 THEN 1 END) AS "EXCESSIVE_SCHEDULED_DURATION",  -- >24 hours
    COUNT(CASE WHEN TRY_CAST("ACTUALELAPSEDTIME" AS INTEGER) > 1440 THEN 1 END) AS "EXCESSIVE_ACTUAL_DURATION",  -- >24 hours
    
    -- DELAY field validation (minutes: positive=late, negative=early)
    COUNT(CASE WHEN TRY_CAST("DEPDELAY" AS INTEGER) < -180 THEN 1 END) AS "EXTREMELY_EARLY_DEPARTURE",  -- >3 hours early
    COUNT(CASE WHEN TRY_CAST("ARRDELAY" AS INTEGER) < -180 THEN 1 END) AS "EXTREMELY_EARLY_ARRIVAL",    -- >3 hours early
    COUNT(CASE WHEN TRY_CAST("DEPDELAY" AS INTEGER) > 600 THEN 1 END) AS "EXTREMELY_LATE_DEPARTURE",    -- >10 hours late
    COUNT(CASE WHEN TRY_CAST("ARRDELAY" AS INTEGER) > 600 THEN 1 END) AS "EXTREMELY_LATE_ARRIVAL",      -- >10 hours late
    
    COUNT(*) AS "TOTAL_RECORDS"
FROM "STAGING_FLIGHTS_RAW";

-- Detailed Time Validation Query - Find all invalid time values
SELECT 
    "TRANSACTIONID",
    "DEPTIME",
    "ARRTIME", 
    "CRSDEPTIME",
    "CRSARRTIME",
    "WHEELSOFF",
    "WHEELSON",
    
    -- Flag invalid times
    CASE WHEN TRY_CAST("DEPTIME" AS INTEGER) >= 2400 THEN 'INVALID_2400_PLUS' 
         WHEN MOD(TRY_CAST("DEPTIME" AS INTEGER), 100) >= 60 THEN 'INVALID_MINUTES'
         ELSE 'VALID' END AS "DEPTIME_STATUS",
         
    CASE WHEN TRY_CAST("ARRTIME" AS INTEGER) >= 2400 THEN 'INVALID_2400_PLUS'
         WHEN MOD(TRY_CAST("ARRTIME" AS INTEGER), 100) >= 60 THEN 'INVALID_MINUTES' 
         ELSE 'VALID' END AS "ARRTIME_STATUS",
         
    CASE WHEN TRY_CAST("CRSDEPTIME" AS INTEGER) >= 2400 THEN 'INVALID_2400_PLUS'
         WHEN MOD(TRY_CAST("CRSDEPTIME" AS INTEGER), 100) >= 60 THEN 'INVALID_MINUTES'
         ELSE 'VALID' END AS "CRSDEPTIME_STATUS",
         
    CASE WHEN TRY_CAST("CRSARRTIME" AS INTEGER) >= 2400 THEN 'INVALID_2400_PLUS'
         WHEN MOD(TRY_CAST("CRSARRTIME" AS INTEGER), 100) >= 60 THEN 'INVALID_MINUTES'
         ELSE 'VALID' END AS "CRSARRTIME_STATUS"

FROM "STAGING_FLIGHTS_RAW"
WHERE TRY_CAST("DEPTIME" AS INTEGER) >= 2400 
   OR TRY_CAST("ARRTIME" AS INTEGER) >= 2400
   OR TRY_CAST("CRSDEPTIME" AS INTEGER) >= 2400  
   OR TRY_CAST("CRSARRTIME" AS INTEGER) >= 2400
   OR TRY_CAST("WHEELSOFF" AS INTEGER) >= 2400
   OR TRY_CAST("WHEELSON" AS INTEGER) >= 2400
   OR MOD(TRY_CAST("DEPTIME" AS INTEGER), 100) >= 60
   OR MOD(TRY_CAST("ARRTIME" AS INTEGER), 100) >= 60
   OR MOD(TRY_CAST("CRSDEPTIME" AS INTEGER), 100) >= 60
   OR MOD(TRY_CAST("CRSARRTIME" AS INTEGER), 100) >= 60;

-- Issue 4: Flight Number Quality Issues
-- Problem: Flight numbers should be numeric and within reasonable ranges
SELECT 
    'Flight Number Quality' AS "ISSUE_TYPE",
    COUNT(CASE WHEN "FLIGHTNUM" IS NULL OR TRIM("FLIGHTNUM") = '' THEN 1 END) AS "MISSING_FLIGHTNUM",
    COUNT(CASE WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) IS NULL AND "FLIGHTNUM" IS NOT NULL THEN 1 END) AS "NON_NUMERIC_FLIGHTNUM",
    COUNT(CASE WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) = 0 THEN 1 END) AS "ZERO_FLIGHTNUM",
    COUNT(CASE WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) < 0 THEN 1 END) AS "NEGATIVE_FLIGHTNUM",
    COUNT(CASE WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) > 9999 THEN 1 END) AS "EXCESSIVE_FLIGHTNUM",  -- Most airlines use 1-4 digits
    COUNT(CASE WHEN LENGTH("FLIGHTNUM") != LENGTH(LTRIM("FLIGHTNUM", '0')) + LENGTH("FLIGHTNUM") - LENGTH(REPLACE("FLIGHTNUM", '0', '')) THEN 1 END) AS "LEADING_ZEROS_LOST",
    COUNT(*) AS "TOTAL_RECORDS"
FROM "STAGING_FLIGHTS_RAW";

-- Detailed Flight Number Analysis
SELECT 
    "FLIGHTNUM",
    COUNT(*) AS "RECORD_COUNT",
    CASE 
        WHEN "FLIGHTNUM" IS NULL OR TRIM("FLIGHTNUM") = '' THEN 'MISSING'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) IS NULL THEN 'NON_NUMERIC'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) = 0 THEN 'ZERO_VALUE'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) < 0 THEN 'NEGATIVE'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) BETWEEN 1 AND 99 THEN 'SINGLE_DOUBLE_DIGIT'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) BETWEEN 100 AND 999 THEN 'TRIPLE_DIGIT'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) BETWEEN 1000 AND 9999 THEN 'FOUR_DIGIT'
        WHEN TRY_CAST("FLIGHTNUM" AS INTEGER) > 9999 THEN 'EXCESSIVE_DIGITS'
        ELSE 'OTHER'
    END AS "FLIGHTNUM_CATEGORY"
FROM "STAGING_FLIGHTS_RAW"
GROUP BY "FLIGHTNUM"
ORDER BY "RECORD_COUNT" DESC, TRY_CAST("FLIGHTNUM" AS INTEGER);

-- Issue 5: Tail Number Standardization Issues
-- Problem: Various non-standard formats (-N963D, NKNO, UNKNOW, blanks)
SELECT 
    'Tail Number Quality' AS "ISSUE_TYPE",
    COUNT(CASE WHEN "TAILNUM" IS NULL OR TRIM("TAILNUM") = '' THEN 1 END) AS "MISSING_TAILNUM",
    COUNT(CASE WHEN "TAILNUM" LIKE 'UNKNOW%' THEN 1 END) AS "UNKNOWN_TAILNUM",
    COUNT(CASE WHEN "TAILNUM" LIKE '-%' THEN 1 END) AS "INVALID_PREFIX_TAILNUM",
    COUNT(CASE WHEN LENGTH("TAILNUM") < 3 AND "TAILNUM" IS NOT NULL THEN 1 END) AS "TOO_SHORT_TAILNUM",
