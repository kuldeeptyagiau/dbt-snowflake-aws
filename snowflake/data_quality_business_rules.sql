-- Rule 1: Standardize Boolean Values
CREATE OR REPLACE VIEW "VW_STANDARDIZED_BOOLEANS" AS
SELECT 
    "TRANSACTIONID",
    -- Standardize CANCELLED field
    CASE 
        WHEN UPPER(TRIM("CANCELLED")) IN ('TRUE', '1', 'T', 'Y', 'YES') THEN 1
        WHEN UPPER(TRIM("CANCELLED")) IN ('FALSE', '0', 'F', 'N', 'NO') THEN 0
        ELSE NULL
    END AS "CANCELLED_STD",
    
    -- Standardize DIVERTED field  
    CASE 
        WHEN UPPER(TRIM("DIVERTED")) IN ('TRUE', '1', 'T', 'Y', 'YES') THEN 1
        WHEN UPPER(TRIM("DIVERTED")) IN ('FALSE', '0', 'F', 'N', 'NO') THEN 0
        ELSE NULL
    END AS "DIVERTED_STD",
    
    -- Original values for comparison
    "CANCELLED" AS "CANCELLED_ORIGINAL",
    "DIVERTED" AS "DIVERTED_ORIGINAL"
FROM "STAGING_FLIGHTS_RAW";

-- Rule 2: Clean Text Fields
CREATE OR REPLACE VIEW "VW_CLEANED_TEXT_FIELDS" AS
SELECT 
    "TRANSACTIONID",
    
    -- Clean airline name by removing code prefix
    CASE 
        WHEN "AIRLINENAME" LIKE '%:%' 
        THEN TRIM(SPLIT_PART("AIRLINENAME", ':', 2))
        ELSE TRIM("AIRLINENAME")
    END AS "AIRLINENAME_CLEAN",
    
    -- Clean origin airport name
    CASE 
        WHEN "ORIGAIRPORTNAME" LIKE '%:%' 
        THEN TRIM(SPLIT_PART("ORIGAIRPORTNAME", ':', 2))
        ELSE TRIM("ORIGAIRPORTNAME")
    END AS "ORIGAIRPORTNAME_CLEAN",
    
    -- Clean destination airport name
    CASE 
        WHEN "DESTAIRPORTNAME" LIKE '%:%' 
        THEN TRIM(SPLIT_PART("DESTAIRPORTNAME", ':', 2))
        ELSE TRIM("DESTAIRPORTNAME")
    END AS "DESTAIRPORTNAME_CLEAN",
    
    -- Original values for comparison
    "AIRLINENAME" AS "AIRLINENAME_ORIGINAL",
    "ORIGAIRPORTNAME" AS "ORIGAIRPORTNAME_ORIGINAL", 
    "DESTAIRPORTNAME" AS "DESTAIRPORTNAME_ORIGINAL"
FROM "STAGING_FLIGHTS_RAW";

-- Rule 3: Time Format Standardization (Enhanced with 2400 correction)
CREATE OR REPLACE VIEW "VW_STANDARDIZED_TIMES" AS
SELECT 
    "TRANSACTIONID",
    
    -- Convert HHMM integer format to proper TIME with 2400 correction
    TRY_CAST(
        CASE 
            WHEN "DEPTIME" IS NULL OR TRIM("DEPTIME") = '' THEN NULL
            WHEN TRY_CAST("DEPTIME" AS INTEGER) = 2400 THEN TIME_FROM_PARTS(0, 0, 0)  -- 2400 = 00:00 next day
            WHEN TRY_CAST("DEPTIME" AS INTEGER) >= 2400 THEN NULL  -- Invalid time
            WHEN MOD(TRY_CAST("DEPTIME" AS INTEGER), 100) >= 60 THEN NULL  -- Invalid minutes
            WHEN LENGTH(TRIM("DEPTIME")) <= 4 AND TRY_CAST("DEPTIME" AS INTEGER) < 2400
            THEN TIME_FROM_PARTS(
                FLOOR(TRY_CAST("DEPTIME" AS INTEGER) / 100),
                MOD(TRY_CAST("DEPTIME" AS INTEGER), 100),
                0
            )
            ELSE NULL
        END AS TIME
    ) AS "DEPTIME_STD",
    
    TRY_CAST(
        CASE 
            WHEN "ARRTIME" IS NULL OR TRIM("ARRTIME") = '' THEN NULL
            WHEN TRY_CAST("ARRTIME" AS INTEGER) = 2400 THEN TIME_FROM_PARTS(0, 0, 0)  -- 2400 = 00:00 next day
            WHEN TRY_CAST("ARRTIME" AS INTEGER) >= 2400 THEN NULL  -- Invalid time
            WHEN MOD(TRY_CAST("ARRTIME" AS INTEGER), 100) >= 60 THEN NULL  -- Invalid minutes
            WHEN LENGTH(TRIM("ARRTIME")) <= 4 AND TRY_CAST("ARRTIME" AS INTEGER) < 2400
            THEN TIME_FROM_PARTS(
                FLOOR(TRY_CAST("ARRTIME" AS INTEGER) / 100),
                MOD(TRY_CAST("ARRTIME" AS INTEGER), 100),
                0
            )
            ELSE NULL
        END AS TIME
    ) AS "ARRTIME_STD",
    
    TRY_CAST(
        CASE 
            WHEN "CRSDEPTIME" IS NULL OR TRIM("CRSDEPTIME") = '' THEN NULL
            WHEN TRY_CAST("CRSDEPTIME" AS INTEGER) = 2400 THEN TIME_FROM_PARTS(0, 0, 0)  -- 2400 = 00:00
            WHEN TRY_CAST("CRSDEPTIME" AS INTEGER) >= 2400 THEN NULL  -- Invalid time
            WHEN MOD(TRY_CAST("CRSDEPTIME" AS INTEGER), 100) >= 60 THEN NULL  -- Invalid minutes
            WHEN LENGTH(TRIM("CRSDEPTIME")) <= 4 AND TRY_CAST("CRSDEPTIME" AS INTEGER) < 2400
            THEN TIME_FROM_PARTS(
                FLOOR(TRY_CAST("CRSDEPTIME" AS INTEGER) / 100),
                MOD(TRY_CAST("CRSDEPTIME" AS INTEGER), 100),
                0
            )
            ELSE NULL
        END AS TIME
    ) AS "CRSDEPTIME_STD",
    
    TRY_CAST(
        CASE 
            WHEN "CRSARRTIME" IS NULL OR TRIM("CRSARRTIME") = '' THEN NULL
            WHEN TRY_CAST("CRSARRTIME" AS INTEGER) = 2400 THEN TIME_FROM_PARTS(0, 0, 0)  -- 2400 = 00:00
            WHEN TRY_CAST("CRSARRTIME" AS INTEGER) >= 2400 THEN NULL  -- Invalid time
            WHEN MOD(TRY_CAST("CRSARRTIME" AS INTEGER), 100) >= 60 THEN NULL  -- Invalid minutes
            WHEN LENGTH(TRIM("CRSARRTIME")) <= 4 AND TRY_CAST("CRSARRTIME" AS INTEGER) < 2400
            THEN TIME_FROM_PARTS(
                FLOOR(TRY_CAST("CRSARRTIME" AS INTEGER) / 100),
                MOD(TRY_CAST("CRSARRTIME" AS INTEGER), 100),
                0
            )
            ELSE NULL
        END AS TIME
    ) AS "CRSARRTIME_STD",
    
    -- Additional time fields with same logic
    TRY_CAST(
        CASE 
            WHEN "WHEELSOFF" IS NULL OR TRIM("WHEELSOFF") = '' THEN NULL
            WHEN TRY_CAST("WHEELSOFF" AS INTEGER) = 2400 THEN TIME_FROM_PARTS(0, 0, 0)
            WHEN TRY_CAST("WHEELSOFF" AS INTEGER) >= 2400 THEN NULL
            WHEN MOD(TRY_CAST("WHEELSOFF" AS INTEGER), 100) >= 60 THEN NULL
            WHEN LENGTH(TRIM("WHEELSOFF")) <= 4 AND TRY_CAST("WHEELSOFF" AS INTEGER) < 2400
            THEN TIME_FROM_PARTS(
                FLOOR(TRY_CAST("WHEELSOFF" AS INTEGER) / 100),
                MOD(TRY_CAST("WHEELSOFF" AS INTEGER), 100),
                0
            )
            ELSE NULL
        END AS TIME
    ) AS "WHEELSOFF_STD",
    
    TRY_CAST(
        CASE 
            WHEN "WHEELSON" IS NULL OR TRIM("WHEELSON") = '' THEN NULL
            WHEN TRY_CAST("WHEELSON" AS INTEGER) = 2400 THEN TIME_FROM_PARTS(0, 0, 0)
            WHEN TRY_CAST("WHEELSON" AS INTEGER) >= 2400 THEN NULL
            WHEN MOD(TRY_CAST("WHEELSON" AS INTEGER), 100) >= 60 THEN NULL
            WHEN LENGTH(TRIM("WHEELSON")) <= 4 AND TRY_CAST("WHEELSON" AS INTEGER) < 2400
            THEN TIME_FROM_PARTS(
                FLOOR(TRY_CAST("WHEELSON" AS INTEGER) / 100),
                MOD(TRY_CAST("WHEELSON" AS INTEGER), 100),
                0
            )
            ELSE NULL
        END AS TIME
    ) AS "WHEELSON_STD",
    
    -- Time validation flags
    CASE WHEN TRY_CAST("DEPTIME" AS INTEGER) = 2400 THEN 'CORRECTED_2400_TO_0000'
         WHEN TRY_CAST("DEPTIME" AS INTEGER) > 2400 THEN 'INVALID_ABOVE_2400'
         WHEN MOD(TRY_CAST("DEPTIME" AS INTEGER), 100) >= 60 THEN 'INVALID_MINUTES' 
         ELSE 'VALID' END AS "DEPTIME_QUALITY_FLAG",
         
    CASE WHEN TRY_CAST("ARRTIME" AS INTEGER) = 2400 THEN 'CORRECTED_2400_TO_0000'
         WHEN TRY_CAST("ARRTIME" AS INTEGER) > 2400 THEN 'INVALID_ABOVE_2400'
         WHEN MOD(TRY_CAST("ARRTIME" AS INTEGER), 100) >= 60 THEN 'INVALID_MINUTES'
         ELSE 'VALID' END AS "ARRTIME_QUALITY_FLAG",
    
    -- Original values
    "DEPTIME" AS "DEPTIME_ORIGINAL",
    "ARRTIME" AS "ARRTIME_ORIGINAL",
    "CRSDEPTIME" AS "CRSDEPTIME_ORIGINAL",
    "CRSARRTIME" AS "CRSARRTIME_ORIGINAL",
    "WHEELSOFF" AS "WHEELSOFF_ORIGINAL",
    "WHEELSON" AS "WHEELSON_ORIGINAL"
FROM "STAGING_FLIGHTS_RAW";

-- Business Rule: Next Day Arrival Detection (Enhanced)
-- Problem: When ARRTIME < DEPTIME, it indicates next-day arrival
CREATE OR REPLACE VIEW "VW_NEXT_DAY_ARRIVAL_LOGIC" AS
SELECT 
    "TRANSACTIONID",
    "DEPTIME",
    "ARRTIME", 
    "CRSDEPTIME",
    "CRSARRTIME",
    
    -- Next day arrival detection
    CASE 
        WHEN TRY_CAST("ARRTIME" AS INTEGER) < TRY_CAST("DEPTIME" AS INTEGER) 
             AND "ARRTIME" IS NOT NULL 
             AND "DEPTIME" IS NOT NULL 
             AND TRY_CAST("ARRTIME" AS INTEGER) < 2400
             AND TRY_CAST("DEPTIME" AS INTEGER) < 2400
        THEN 1
        WHEN TRY_CAST("ARRTIME" AS INTEGER) = 2400 
             AND TRY_CAST("DEPTIME" AS INTEGER) > 1200  -- Departed after noon, arrived at midnight
        THEN 1  
        ELSE 0
    END AS "IS_NEXT_DAY_ARRIVAL",
    
    -- Time correction needed flag
    CASE 
        WHEN TRY_CAST("DEPTIME" AS INTEGER) = 2400 
          OR TRY_CAST("ARRTIME" AS INTEGER) = 2400
          OR TRY_CAST("CRSDEPTIME" AS INTEGER) = 2400
          OR TRY_CAST("CRSARRTIME" AS INTEGER) = 2400
        THEN 'NEEDS_2400_CORRECTION'
        WHEN TRY_CAST("DEPTIME" AS INTEGER) > 2400
          OR TRY_CAST("ARRTIME" AS INTEGER) > 2400  
        THEN 'INVALID_TIME_VALUE'
        ELSE 'NO_CORRECTION_NEEDED'
    END AS "TIME_CORRECTION_STATUS"
    
FROM "STAGING_FLIGHTS_RAW"
WHERE "DEPTIME" IS NOT NULL OR "ARRTIME" IS NOT NULL;
