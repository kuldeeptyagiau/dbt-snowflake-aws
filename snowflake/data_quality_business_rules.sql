FROM "STAGING_FLIGHTS_RAW";

-- Issue 6: Flight Date Quality Issues
-- Problem: FLIGHTDATE in YYYYMMDD format needs validation
-- Sample values: 19920912, 20040903, 20010103, etc.
SELECT 
    'Flight Date Quality' AS "ISSUE_TYPE",
    COUNT(CASE WHEN "FLIGHTDATE" IS NULL OR TRIM("FLIGHTDATE") = '' THEN 1 END) AS "MISSING_FLIGHTDATE",
    COUNT(CASE WHEN LENGTH("FLIGHTDATE") != 8 THEN 1 END) AS "INCORRECT_DATE_LENGTH",
    COUNT(CASE WHEN TRY_CAST("FLIGHTDATE" AS INTEGER) IS NULL AND "FLIGHTDATE" IS NOT NULL THEN 1 END) AS "NON_NUMERIC_DATE",
    COUNT(CASE WHEN TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') IS NULL AND "FLIGHTDATE" IS NOT NULL THEN 1 END) AS "INVALID_DATE_VALUES",
    
    -- Date range validation
    COUNT(CASE WHEN TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') < '1980-01-01' THEN 1 END) AS "TOO_OLD_DATES",
    COUNT(CASE WHEN TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') > CURRENT_DATE() + 365 THEN 1 END) AS "FUTURE_DATES",
    
    -- Year validation
    COUNT(CASE WHEN SUBSTR("FLIGHTDATE", 1, 4)::INTEGER < 1980 THEN 1 END) AS "PRE_1980_YEARS",
    COUNT(CASE WHEN SUBSTR("FLIGHTDATE", 1, 4)::INTEGER > YEAR(CURRENT_DATE()) + 1 THEN 1 END) AS "FUTURE_YEARS",
    
    -- Month validation (should be 01-12)
    COUNT(CASE WHEN SUBSTR("FLIGHTDATE", 5, 2)::INTEGER NOT BETWEEN 1 AND 12 THEN 1 END) AS "INVALID_MONTHS",
    
    -- Day validation (should be 01-31)
    COUNT(CASE WHEN SUBSTR("FLIGHTDATE", 7, 2)::INTEGER NOT BETWEEN 1 AND 31 THEN 1 END) AS "INVALID_DAYS",
    
    COUNT(*) AS "TOTAL_RECORDS"
FROM "STAGING_FLIGHTS_RAW";

-- Detailed FLIGHTDATE Analysis
SELECT 
    "FLIGHTDATE",
    TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') AS "PARSED_DATE",
    SUBSTR("FLIGHTDATE", 1, 4) AS "YEAR_PART",
    SUBSTR("FLIGHTDATE", 5, 2) AS "MONTH_PART", 
    SUBSTR("FLIGHTDATE", 7, 2) AS "DAY_PART",
    
    CASE 
        WHEN "FLIGHTDATE" IS NULL OR TRIM("FLIGHTDATE") = '' THEN 'MISSING'
        WHEN LENGTH("FLIGHTDATE") != 8 THEN 'WRONG_LENGTH'
        WHEN TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') IS NULL THEN 'INVALID_DATE'
        WHEN TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') < '1980-01-01' THEN 'TOO_OLD'
        WHEN TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') > CURRENT_DATE() + 365 THEN 'FUTURE_DATE'
        WHEN SUBSTR("FLIGHTDATE", 5, 2)::INTEGER NOT BETWEEN 1 AND 12 THEN 'INVALID_MONTH'
        WHEN SUBSTR("FLIGHTDATE", 7, 2)::INTEGER NOT BETWEEN 1 AND 31 THEN 'INVALID_DAY'
        ELSE 'VALID'
    END AS "DATE_QUALITY_STATUS",
    
    COUNT(*) AS "RECORD_COUNT"
    
FROM "STAGING_FLIGHTS_RAW"
WHERE "FLIGHTDATE" IS NOT NULL
GROUP BY "FLIGHTDATE", TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD'), 
         SUBSTR("FLIGHTDATE", 1, 4), SUBSTR("FLIGHTDATE", 5, 2), SUBSTR("FLIGHTDATE", 7, 2)
HAVING TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') IS NULL 
    OR TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') < '1980-01-01'
    OR TRY_TO_DATE("FLIGHTDATE", 'YYYYMMDD') > CURRENT_DATE() + 365
    OR LENGTH("FLIGHTDATE") != 8
ORDER BY "RECORD_COUNT" DESC;

